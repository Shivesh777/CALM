"""Proceed-protocol pools on a PatchTST backbone ("base9"): pre-scripts that run pretraining, GD and Proceed in the
authors' code (OnlineTSF / DynaME repo, released PatchTST hyper-parameters from scripts/{pretrain,online}/PatchTST)
with prediction dumps, and the job lists for our harness (PatchTSTo = the same PatchTST implementation, trained in our
harness with the same pretraining configuration; pool as in base7).

  python make_pre9.py [seed_offset]        -> pre/base9_<DS>[_s20xx].sh, jobs/base9_<DS>[_s20xx].jsonl

ECL / Traffic are left out: their released PatchTST pretraining uses 2-3-GPU distributed training.
ETTh2 at H = 24: Proceed's PatchTST script releases no configuration; the H = 48 configuration is used (flagged).
"""
import sys

sys.path.insert(0, ".")
from make_jobs import write
POOL = [  # as make_pre7.POOL (not imported: make_pre7 writes files on import)
    dict(kind="frozen", name="frozen"),
    dict(kind="rls", lam=1.0, solve_every=24, name="rls1"),
    dict(kind="rls", lam=0.9999, solve_every=24, name="rls.9999"),
    dict(kind="rls", lam=0.999, solve_every=24, name="rls.999"),
    dict(kind="linrls", lam=1.0, name="lin1"),
    dict(kind="linrls", lam=0.999, name="lin.999"),
    dict(kind="efc", lam=1.0, name="efc1"),
    dict(kind="efc", lam=0.999, name="efc.999"),
    dict(kind="snaive", name="snaive"),
]
AGGS = [dict(name="naive", eta=2.0, share=1e-4, hscale=False), dict(name="cal", eta=0.5, share=1e-4, hscale=True),
        dict(name="cal_cum", eta=0.5, share=1e-4, hscale=True, xh="cum"), dict(name="uniform", eta=0.0)]

# their name, our name, seq_len, patience, GD online lr, Proceed batch size, extra Proceed flags,
# per H: (mid, btl, lr, online lr)
P = {
    "ETTh2": ("ETTh2", "ETTh2", 336, 10, "0.00003", 16, "",
              {24: (200, 48, "0.003", "0.0003"), 48: (200, 48, "0.003", "0.0003"), 96: (200, 48, "0.0003", "0.00001")}),
    "ETTm1": ("ETTm1", "ETTm1", 512, 10, "0.0000003", 16, "--wo_clip",
              {24: (250, 48, "0.001", "0.00001"), 48: (250, 48, "0.001", "0.00001"), 96: (150, 48, "0.001", "0.00001")}),
    "Weather": ("Weather", "weather", 512, 20, "0.0000001", 8, "",
                {24: (150, 32, "0.0001", "0.0000003"), 48: (150, 48, "0.0001", "0.0000003"),
                 96: (150, 64, "0.000003", "0.0000001")}),
}

HEAD = """#!/bin/bash
# Proceed-protocol baselines (PatchTST, {DS}, L={L}) with prediction dumps for pooling as external experts.
# Generated by make_pre9.py from the released OnlineTSF PatchTST scripts.
W=/kaggle/working
{SEEDLINE}chain () {{
  H=$1; G=$2; MID=$3; BTL=$4; LR=$5; OLR=$6
  COMMON="--dataset {DS} --border_type online --model PatchTST --seq_len {L} --pred_len $H --itr 1 --gpu $G"
  python -u run.py $COMMON --pin_gpu True --reduce_bs False --save_opt --batch_size 128 --train_epochs 100 --pct 0.4 \\
      --patience {PAT} --learning_rate 0.0001 > $W/baseline_logs/pretrain_{DS}_H$H.log 2>&1
  DUMP_PREDS=$W/preds/GD__{DS}__L{L}__H$H python -u run.py $COMMON --online_method Online --online_learning_rate {GDLR} \\
      --pin_gpu True --reduce_bs False --save_opt --only_test > $W/baseline_logs/gd_{DS}_H$H.log 2>&1
  DUMP_PREDS=$W/preds/Proceed__{DS}__L{L}__H$H python -u run.py $COMMON --batch_size {PCBS} --tune_mode down_up \\
      --concept_dim $MID --val_online_lr --diff_online_lr --pretrain {EXTRA} --save_opt --online_method Proceed \\
      --bottleneck_dim $BTL --online_learning_rate $OLR --learning_rate $LR --lradj type3 > $W/baseline_logs/proceed_{DS}_H$H.log 2>&1
  grep -h "^mse:" $W/baseline_logs/*_{DS}_H$H.log
}}
"""


def main(off=0):
    sfx = f"_s{2021 + off}" if off else ""
    for key, (ds, ours, L, pat, gdlr, pcbs, extra, hp) in P.items():
        s = HEAD.format(DS=ds, L=L, PAT=pat, GDLR=gdlr, PCBS=pcbs, EXTRA=extra,
                        SEEDLINE=f"export SEED_OFFSET={off}\n" if off else "")
        s = s.replace("--pretrain  --save_opt", "--pretrain --save_opt")
        a = [f"chain {H} {g} {hp[H][0]} {hp[H][1]} {hp[H][2]} {hp[H][3]}" for H, g in ((24, 0), (48, 1), (96, 0))]
        s += f"{a[0]} &\n{a[1]} &\nwait\n{a[2]}\nls -la $W/preds\n"
        open(f"pre/base9_{key}{sfx}.sh", "w").write(s)
        jobs = []
        for H in (24, 48, 96):
            ext = [dict(kind="external", path=f"/kaggle/working/preds/GD__{ds}__L{L}__H{H}_itr0.npz", name="ext_gd"),
                   dict(kind="external", path=f"/kaggle/working/preds/Proceed__{ds}__L{L}__H{H}_itr0.npz",
                        name="ext_proceed", val_mode="frozen")]
            # head input of PatchTST = d_model x patches: 672 on ETTh2, 8192 at L = 512 with d_model 128; there the
            # output-layer refits re-solve every 192 steps instead of 24 (one 8193-dim solve costs ~1-2 s in fp64)
            pool = [dict(e, solve_every=192) if (e["kind"] == "rls" and ours != "ETTh2") else e for e in POOL]
            jobs.append(dict(model="PatchTSTo", dataset=ours, seq_len=L, pred_len=H, split="online", ema=False,
                             diag=False, seed=2021 + off, experts=pool + ext, aggs=AGGS, every=1, agg_buckets=12,
                             dump_stats=True, tag="base9"))
        write(jobs, f"jobs/base9_{key}{sfx}.jsonl")
        print("wrote", f"pre/base9_{key}{sfx}.sh", f"jobs/base9_{key}{sfx}.jsonl")


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 0)
